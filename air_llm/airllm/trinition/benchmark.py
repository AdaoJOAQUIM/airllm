"""
The "killer experiment": does changing the *algebra* (not the parameter count)
actually buy anything?

This is the falsification harness for the hypothesis discussed around Trinition /
Atangana operators. It compares three composition algebras at **strictly equal
readout-parameter budgets** on two synthetic tasks:

* Task A -- SO(3) rotation composition (3D, non-commutative). Quaternions are the
  *known-correct* algebra here, so this is a control: if the matched algebra wins,
  the harness is measuring the right thing. The real question is how close
  Trinition gets.

* Task B -- a fractional-memory (non-Markovian) process. This is where an
  Atangana-style fractional operator is expected to help, if anywhere.

Design choices that keep it honest:
  - Every model emits a feature vector of the SAME dimension and is read out by
    the SAME-sized ridge-regression head. Only the composition rule differs, so
    any gap is attributable to the algebra, not to capacity.
  - Ground truth is generated by exact mathematics (exact quaternion composition;
    exact fractional differencing), independent of any model.
  - Results are whatever they are. A loss for Trinition is reported as a loss.

Requires numpy. Run with::

    python -m airllm.trinition.benchmark           # full run
    python -m airllm.trinition.benchmark --quick   # smaller, faster

Nothing here touches AirLLM's inference path.
"""

from __future__ import annotations

import argparse
from typing import Dict, List, Tuple

import numpy as np

from .trinition import make_structure_constants
from .operators import gl_weights


# ---------------------------------------------------------------------------
# Algebra primitives (vectorized over a batch of N samples)
# ---------------------------------------------------------------------------

def _trinition_table() -> np.ndarray:
    """Default Trinition structure constants as a (3, 3, 3) array."""
    return np.asarray(make_structure_constants(), dtype=float)


def trinition_product(x: np.ndarray, y: np.ndarray, C: np.ndarray) -> np.ndarray:
    """Batched Trinition product. x, y: (N, 3) -> (N, 3)."""
    return np.einsum("nk,nl,klm->nm", x, y, C)


def real_diag_product(x: np.ndarray, y: np.ndarray) -> np.ndarray:
    """Component-wise (commutative, associative) product in R^3 -- the 'wrong'
    structure for rotations. x, y: (N, 3) -> (N, 3)."""
    return x * y


def quat_from_axis_angle(aa: np.ndarray) -> np.ndarray:
    """Exponential map: axis-angle (N, 3) -> unit quaternion (N, 4) [w, x, y, z]."""
    theta = np.linalg.norm(aa, axis=1, keepdims=True)          # (N, 1)
    safe = np.where(theta < 1e-12, 1.0, theta)
    axis = aa / safe
    half = theta / 2.0
    w = np.cos(half)
    xyz = axis * np.sin(half)
    return np.concatenate([w, xyz], axis=1)


def quat_mul(p: np.ndarray, q: np.ndarray) -> np.ndarray:
    """Hamilton product of batched quaternions. p, q: (N, 4) -> (N, 4)."""
    pw, px, py, pz = p[:, 0], p[:, 1], p[:, 2], p[:, 3]
    qw, qx, qy, qz = q[:, 0], q[:, 1], q[:, 2], q[:, 3]
    w = pw * qw - px * qx - py * qy - pz * qz
    x = pw * qx + px * qw + py * qz - pz * qy
    y = pw * qy - px * qz + py * qw + pz * qx
    z = pw * qz + px * qy - py * qx + pz * qw
    return np.stack([w, x, y, z], axis=1)


# ---------------------------------------------------------------------------
# Ridge-regression readout (closed form) + learning curve
# ---------------------------------------------------------------------------

def ridge_fit(X: np.ndarray, Y: np.ndarray, lam: float = 1e-6) -> np.ndarray:
    """Closed-form ridge: returns W mapping [X | 1] -> Y."""
    n, d = X.shape
    Xb = np.concatenate([X, np.ones((n, 1))], axis=1)
    A = Xb.T @ Xb + lam * np.eye(d + 1)
    return np.linalg.solve(A, Xb.T @ Y)


def ridge_predict(X: np.ndarray, W: np.ndarray) -> np.ndarray:
    Xb = np.concatenate([X, np.ones((X.shape[0], 1))], axis=1)
    return Xb @ W


def _mse(a: np.ndarray, b: np.ndarray) -> float:
    return float(np.mean((a - b) ** 2))


def readout_params(feat_dim: int, out_dim: int) -> int:
    """Parameter count of the linear head (weights + bias)."""
    return (feat_dim + 1) * out_dim


# ---------------------------------------------------------------------------
# Task A: SO(3) rotation composition
# ---------------------------------------------------------------------------

def make_task_a(n: int, length: int, rng: np.random.Generator,
                step: float = 0.6) -> Tuple[np.ndarray, np.ndarray]:
    """Sequences of small rotations (as axis-angle 3-vectors) and the target:
    the exact composed unit quaternion (4D). Ground truth uses exact quaternion
    composition and is model-independent."""
    seqs = rng.normal(scale=step, size=(n, length, 3))
    acc = quat_from_axis_angle(seqs[:, 0, :])
    for t in range(1, length):
        acc = quat_mul(acc, quat_from_axis_angle(seqs[:, t, :]))
    # normalize (it already is, up to float error)
    acc = acc / np.linalg.norm(acc, axis=1, keepdims=True)
    return seqs, acc


def _fold(seqs: np.ndarray, lift, product) -> np.ndarray:
    """Left-fold each sequence under a model's lift + product."""
    acc = lift(seqs[:, 0, :])
    for t in range(1, seqs.shape[1]):
        acc = product(acc, lift(seqs[:, t, :]))
    return acc


def features_task_a(seqs: np.ndarray, model: str, C: np.ndarray) -> np.ndarray:
    """Compose a sequence into a 4D feature vector under the chosen algebra.
    All models emit dim 4 so the readout has identical size."""
    if model == "quaternion":
        feat = _fold(seqs, quat_from_axis_angle, quat_mul)            # (N, 4)
        return feat
    if model == "trinition":
        feat = _fold(seqs, lambda v: v.copy(),
                     lambda x, y: trinition_product(x, y, C))         # (N, 3)
    elif model == "real":
        feat = _fold(seqs, lambda v: v.copy(), real_diag_product)     # (N, 3)
    else:
        raise ValueError(model)
    norm = np.linalg.norm(feat, axis=1, keepdims=True)
    return np.concatenate([feat, norm], axis=1)                       # (N, 4)


def sweep_trinition_deformation(rng: np.random.Generator, n_train: int,
                                length: int, n_test: int,
                                alphas: List[float]) -> List[Tuple[float, float]]:
    """Give Trinition its own 'deformability' knob: sweep the algebra parameter
    alpha and report test MSE on Task A for each. Tests the thesis's central
    claim -- that a *deformed* algebra can match the structure -- rather than
    judging one arbitrary table."""
    seqs_tr, y_tr = make_task_a(n_train, length, rng)
    seqs_te, y_te = make_task_a(n_test, length, rng)
    out = []
    for al in alphas:
        C = np.asarray(make_structure_constants(alpha=al), dtype=float)
        Xtr = features_task_a(seqs_tr, "trinition", C)
        Xte = features_task_a(seqs_te, "trinition", C)
        W = ridge_fit(Xtr, y_tr)
        out.append((al, _mse(ridge_predict(Xte, W), y_te)))
    return out


def run_task_a(rng: np.random.Generator, sizes: List[int],
               length: int, n_test: int) -> Dict[str, List[float]]:
    C = _trinition_table()
    models = ["real", "quaternion", "trinition"]
    seqs_te, y_te = make_task_a(n_test, length, rng)
    feats_te = {m: features_task_a(seqs_te, m, C) for m in models}
    results = {m: [] for m in models}
    for n in sizes:
        seqs_tr, y_tr = make_task_a(n, length, rng)
        for m in models:
            Xtr = features_task_a(seqs_tr, m, C)
            W = ridge_fit(Xtr, y_tr)
            pred = ridge_predict(feats_te[m], W)
            results[m].append(_mse(pred, y_te))
    return results


# ---------------------------------------------------------------------------
# Task B: fractional-memory (non-Markovian) process
# ---------------------------------------------------------------------------

def make_task_b(n: int, history: int, rng: np.random.Generator,
                alpha: float = 0.5) -> Tuple[np.ndarray, np.ndarray]:
    """Generate samples (past_window, next_value) from a fractional-difference
    process: y_t is a long-memory combination of past innovations governed by
    order alpha. Returns X_hist (n, history) and y (n,)."""
    w = np.asarray(gl_weights(-alpha, history))   # fractional *integration* kernel
    X = np.zeros((n, history))
    y = np.zeros(n)
    for i in range(n):
        # Innovations driving a long-memory trajectory; the model sees the past
        # y-window and predicts the next value y_t = sum_k w_k * eps_{t-k}.
        eps = rng.normal(size=history + 1)
        traj = np.convolve(eps, w, mode="full")[:history + 1]
        X[i] = traj[:history]
        y[i] = traj[history]
    return X, y


def features_task_b_real(X: np.ndarray, k: int) -> np.ndarray:
    """Real AR(k) baseline: the last k lags."""
    return X[:, -k:]


def features_task_b_frac(X: np.ndarray, alpha: float, memory: int) -> np.ndarray:
    """Fractional feature: a single Gruenwald-Letnikov fractional derivative of
    order alpha applied across the window (1 feature), plus the last value."""
    w = np.asarray(gl_weights(alpha, memory - 1))            # (memory,)
    window = X[:, -memory:]
    frac = window[:, ::-1] @ w                               # (N,)
    last = X[:, -1]
    return np.stack([frac, last], axis=1)                   # (N, 2)


def run_task_b(rng: np.random.Generator, sizes: List[int], history: int,
               n_test: int, alpha: float) -> Dict[str, List[Tuple[int, float]]]:
    X_te, y_te = make_task_b(n_test, history, rng, alpha)
    y_te = y_te.reshape(-1, 1)
    out: Dict[str, List[Tuple[int, float]]] = {}

    # Fractional model: tiny (2-feature) head, fixed across sizes.
    frac_curve = []
    for n in sizes:
        Xtr, ytr = make_task_b(n, history, rng, alpha)
        Ftr = features_task_b_frac(Xtr, alpha, history)
        W = ridge_fit(Ftr, ytr.reshape(-1, 1))
        pred = ridge_predict(features_task_b_frac(X_te, alpha, history), W)
        frac_curve.append((readout_params(2, 1), _mse(pred, y_te)))
    out[f"fractional(alpha={alpha}, 2 feat)"] = frac_curve

    # Real AR(k) baselines at increasing k (more params).
    for k in (2, 4, 8):
        curve = []
        for n in sizes:
            Xtr, ytr = make_task_b(n, history, rng, alpha)
            Ftr = features_task_b_real(Xtr, k)
            W = ridge_fit(Ftr, ytr.reshape(-1, 1))
            pred = ridge_predict(features_task_b_real(X_te, k), W)
            curve.append((readout_params(k, 1), _mse(pred, y_te)))
        out[f"real AR(k={k})"] = curve
    return out


# ---------------------------------------------------------------------------
# Reporting
# ---------------------------------------------------------------------------

def _fmt_row(label: str, vals: List[str], width: int = 12) -> str:
    return f"  {label:<26}" + "".join(f"{v:>{width}}" for v in vals)


def main(argv=None) -> str:
    parser = argparse.ArgumentParser()
    parser.add_argument("--quick", action="store_true")
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args(argv)

    rng = np.random.default_rng(args.seed)
    sizes = [50, 200, 800] if args.quick else [50, 200, 800, 3200]
    length = 6
    n_test = 2000
    alpha_b = 0.5

    lines: List[str] = []
    lines.append("=" * 72)
    lines.append(" Trinition / Atangana falsification harness")
    lines.append(" (equal readout-parameter budget; only the algebra changes)")
    lines.append("=" * 72)

    # ---- Task A ----
    a = run_task_a(rng, sizes, length, n_test)
    lines.append("")
    lines.append("Task A -- SO(3) rotation composition (target: exact composed quaternion)")
    lines.append("  Test MSE vs training-set size. Lower is better. All heads: %d params."
                 % readout_params(4, 4))
    lines.append(_fmt_row("model \\ N", [str(s) for s in sizes]))
    for m in ("real", "quaternion", "trinition"):
        lines.append(_fmt_row(m, [f"{v:.4f}" for v in a[m]]))
    best_big = min(("real", "quaternion", "trinition"), key=lambda m: a[m][-1])
    lines.append(f"  -> best at largest N: {best_big}")

    # Give Trinition its deformability knob a fair shot.
    sweep = sweep_trinition_deformation(
        rng, n_train=sizes[-1], length=length, n_test=n_test,
        alphas=[0.0, 0.25, 0.5, 0.75, 1.0, 1.5, 2.0])
    lines.append("")
    lines.append("  Deformation sweep (Trinition alpha vs Task A MSE) -- the thesis's")
    lines.append("  core 'controllable algebra' claim, given a fair shot:")
    lines.append(_fmt_row("alpha", [f"{al:g}" for al, _ in sweep], width=9))
    lines.append(_fmt_row("MSE", [f"{m:.4f}" for _, m in sweep], width=9))
    best_al, best_al_mse = min(sweep, key=lambda t: t[1])
    lines.append(f"  -> best alpha={best_al:g} gives MSE {best_al_mse:.4f} "
                 f"(quaternion control: {a['quaternion'][-1]:.4f})")

    # ---- Task B ----
    b = run_task_b(rng, sizes, history=16, n_test=n_test, alpha=alpha_b)
    lines.append("")
    lines.append("Task B -- fractional-memory process (non-Markovian, alpha=%.2f)" % alpha_b)
    lines.append("  Each cell: test MSE. #params shown per model. Lower is better.")
    lines.append(_fmt_row("model \\ N", [str(s) for s in sizes]))
    for label, curve in b.items():
        params = curve[0][0]
        mses = [f"{mse:.4f}" for _, mse in curve]
        lines.append(_fmt_row(f"{label} [{params}p]", mses))

    # ---- Verdict ----
    lines.append("")
    lines.append("-" * 72)
    lines.append("Honest read-out:")
    lines.append("  * Task A is a CONTROL. Quaternions are the correct algebra for")
    lines.append("    SO(3); they should win. Whether Trinition beats the real-diagonal")
    lines.append("    baseline tells you if its 3D product captures *any* rotation")
    lines.append("    structure.")
    lines.append("  * Task B is where a fractional operator earns its keep: if the")
    lines.append("    2-feature fractional head matches or beats a wider real AR head,")
    lines.append("    that is a genuine (if modest) parameter-efficiency win.")
    lines.append("  * Neither task licenses 'the industry is destroyed'. They locate")
    lines.append("    exactly where an algebra change helps and where it does not.")
    lines.append("-" * 72)

    report = "\n".join(lines)
    print(report)
    return report


if __name__ == "__main__":
    main()
